export type { CP };

export function codeOf(cp: CP): CountryCode {
  return cp === "ru" ? "RU" : "BY";
}
export function parseCountry(v: string): CP | null {
  return v === "ru" || v === "by" ? v : null;
}
export function otherCountry(cp: CP): CP {
  return cp === "ru" ? "by" : "ru";
}
export function countryName(cp: CP): string {
  return COUNTRY[codeOf(cp)].name;
}
export function currencyOf(cp: CP) {
  return COUNTRY[codeOf(cp)].currency;
}
export function registerHref(cp: CP, extra?: Record<string, string>): string {
  const q = new URLSearchParams({ country: codeOf(cp), ...(extra ?? {}) });
  return `/register?${q.toString()}`;
}
export function planPrice(cp: CP, plan: Exclude<PlanId, "FREE">): string {
  return formatMoney(PLAN_PRICES[codeOf(cp)][plan], currencyOf(cp));
}

export function contactEmail(): string {
  return process.env.CONTACT_EMAIL || "hello@qronus.example";
}

